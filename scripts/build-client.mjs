#!/usr/bin/env node
/**
 * Zero-dependency client build: concatenate client-src/*.js (sorted by filename)
 * into client.js, wrapped in the browser module-loader envelope.
 * The browser half must be one loadable file; the sources stay reviewable.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const srcDir = join(root, 'client-src');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const files = readdirSync(srcDir).filter((f) => f.endsWith('.js')).sort();
if (files.length === 0) throw new Error('client-src is empty');

import { createHash } from 'node:crypto';
const body = files.map((f) => {
  const text = readFileSync(join(srcDir, f), 'utf8');
  return '/* ===== ' + f + ' ===== */\n' + text.replace(/\n+$/, '') + '\n';
}).join('\n');

const out = [
  '/* ' + pkg.name + ' client half — generated by scripts/build-client.mjs; do not edit. */',
  'window.__ModuleLoader__.load({',
  '  id: ' + JSON.stringify(pkg.name) + ',',
  '  factory(require) {',
  '    const React = require("react");',
  '    const WB_BUILD = ' + JSON.stringify(pkg.version + '+' + createHash('sha256').update(body).digest('hex').slice(0, 8)) + ';',
  body.split('\n').map((line) => line.length ? '    ' + line : line).join('\n'),
  '  },',
  '});',
  '',
].join('\n');
writeFileSync(join(root, 'client.js'), out);
console.log('built client.js from ' + files.length + ' sources (' + out.length + ' bytes)');
